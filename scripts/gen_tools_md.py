"""Generate TOOLS.md from agent.tools.TOOLS. Run: python scripts/gen_tools_md.py"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from agent.tools import TOOLS  # noqa: E402

TARGETS = [ROOT / "TOOLS.md"]
COPY = ROOT.parent / "TOOLS.md"   # D:\Vision-Pipeline\TOOLS.md, written when that folder exists


def _type(s):
    if "enum" in s:
        return " / ".join(repr(v) for v in s["enum"])
    t = s.get("type", "any")
    if t == "array":
        return f"array of {_type(s.get('items', {}))}"
    if t == "object" and s.get("properties"):
        return "{" + ", ".join(f"{k}: {_type(v)}" for k, v in s["properties"].items()) + "}"
    rng = [f"min {s['minimum']}" if "minimum" in s else "", f"max {s['maximum']}" if "maximum" in s else ""]
    rng = ", ".join(r for r in rng if r)
    return t + (f" ({rng})" if rng else "")


def _esc(t):
    return str(t).replace("|", "\\|").replace("\n", " ")


def render():
    out = ["# VLM agent tools", "",
           "Generated by `scripts/gen_tools_md.py` from `agent/tools.py` (TOOLS). Do not edit by hand;",
           "a unit test fails if this file is out of date.", "",
           "| Tool | Runs on | Description | Inputs | Outputs |", "|---|---|---|---|---|"]
    for n, s in TOOLS.items():
        props = s["args"].get("properties", {})
        req = set(s["args"].get("required", []))
        ins = "<br>".join(f"`{k}`{'' if k in req else '?'}: {_type(v)}" for k, v in props.items()) or "none"
        out.append(f"| `{n}` | {s['runs_on']} | {_esc(s['description'])} | {_esc(ins)} | {_esc(s['outputs'])} |")
    return "\n".join(out) + "\n"


def main():
    text = render()
    targets = TARGETS + ([COPY] if COPY.parent.exists() else [])
    for p in targets:
        p.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", p)


if __name__ == "__main__":
    main()
